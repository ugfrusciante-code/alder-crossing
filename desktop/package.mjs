import {cp,mkdir,writeFile,readFile,access,rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
if(process.platform!=='darwin')throw new Error('This packager creates a local macOS build.');
await access(path.join(root,'dist/index.html'));
const output=path.resolve(root,'../Alder Crossing.app');
await rm(output,{recursive:true,force:true});
await cp(path.join(root,'node_modules/electron/dist/Electron.app'),output,{recursive:true,verbatimSymlinks:true});
const contents=path.join(output,'Contents'),appRoot=path.join(contents,'Resources/app');
await mkdir(path.join(appRoot,'desktop'),{recursive:true});
await cp(path.join(root,'dist'),path.join(appRoot,'dist'),{recursive:true});
await cp(path.join(root,'desktop/main.cjs'),path.join(appRoot,'desktop/main.cjs'));
const pkg=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
await writeFile(path.join(appRoot,'package.json'),JSON.stringify({name:pkg.name,version:pkg.version,main:'desktop/main.cjs'}));
await cp(path.join(root,'node_modules/electron/dist/LICENSES.chromium.html'),path.join(contents,'Resources/LICENSES.chromium.html'));
await cp(path.join(root,'node_modules/electron/LICENSE'),path.join(contents,'Resources/LICENSE.electron.txt'));
await cp(path.join(root,'node_modules/three/LICENSE'),path.join(contents,'Resources/LICENSE.three.txt'));
const plist=path.join(contents,'Info.plist');
for(const[key,value]of Object.entries({CFBundleName:'Alder Crossing',CFBundleDisplayName:'Alder Crossing',CFBundleIdentifier:'com.cozyvillage.alder',CFBundleShortVersionString:pkg.version}))execFileSync('/usr/libexec/PlistBuddy',['-c',`Set :${key} ${value}`,plist]);
execFileSync('/usr/bin/codesign',['--force','--deep','--sign','-',output],{stdio:'inherit'});
console.log(`Desktop build ready: ${output}`);
